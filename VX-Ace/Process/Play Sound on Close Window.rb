$imported = {} if $imported.nil?
$imported[:r2_pswcm] = 1.01        # Play Sound When Closing Message

class Window_Message < Window_Base
  def close_and_wait
    close
    Fiber.yield until all_close?
    RPG::SE.new(R2_MESSAGE_CLOSE::AUDSND, 80, 0).play
  end
end
